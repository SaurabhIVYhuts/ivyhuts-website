// ---- Slide: Your Hiring Path ----
function buildHiringPathSlide(pptx, n, pageNum, totalPages) {
    const { slide } = DS.frame(pptx, { sectionLabel: "Hiring", title: "Your Hiring Path" });
    slide.addText(`For your strongest match: ${n.primaryCareerTitle || ""}`, { x: MARGIN, y: CONTENT_TOP, w: CONTENT_W, h: 0.32, fontSize: 12.5, bold: true, color: COLORS.rose, fontFace: FONT });

    const gridTop = CONTENT_TOP + 0.42;
    const colW = (CONTENT_W - GUTTER) / 2;
    const rowH = (CONTENT_BOTTOM - gridTop - GUTTER) / 2;
    const interviewItems = n.readiness.interviewAreas.flatMap((group) => group.items.slice(0, 2).map((item) => `${group.label}: ${item}`)).slice(0, 5);
    const quadrants = [
        { num: "01", title: "Skills to Develop", items: n.readiness.skillsToDevelop },
        { num: "02", title: "Portfolio Evidence", items: n.readiness.projectEvidence.length > 0 ? n.readiness.projectEvidence : n.readiness.portfolioExpectations },
        { num: "03", title: "Interview Preparation", items: interviewItems },
        { num: "04", title: "Typical Entry Routes", items: n.readiness.entryRoutes },
    ];
    quadrants.forEach((q, i) => {
        const col = i % 2;
        const row = Math.floor(i / 2);
        const x = MARGIN + col * (colW + GUTTER);
        const y = gridTop + row * (rowH + GUTTER);
        slide.addShape("roundRect", { x, y, w: colW, h: rowH, rectRadius: RADIUS_CARD, fill: { color: COLORS.white }, line: CARD_LINE });
        slide.addText(q.num, { x: x + colW - 0.9, y: y + 0.1, w: 0.75, h: 0.5, fontSize: 26, bold: true, color: COLORS.track, align: "right", fontFace: FONT });
        slide.addText(q.title.toUpperCase(), { x: x + 0.24, y: y + 0.2, w: colW - 1.1, h: 0.3, fontSize: TYPE.sectionLabel, bold: true, color: COLORS.purple, charSpacing: 1, fontFace: FONT });
        slide.addText(
            q.items.slice(0, 5).map((item) => ({ text: item, options: { bullet: { code: "2022", color: COLORS.rose }, breakLine: true } })),
            { x: x + 0.24, y: y + 0.56, w: colW - 0.48, h: rowH - 0.72, fontSize: 12.5, color: COLORS.inkSoft, fontFace: FONT, valign: "top", lineSpacingMultiple: 1.28 }
        );
    });

    DS.footer(slide, pageNum, totalPages);
    return slide;
}

// ---- Slide: Suggested Preparation Path ----
