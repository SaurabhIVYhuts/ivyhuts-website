// ---- Slide: Closing / Your Next Move ----
function buildClosingSlide(pptx, n, pageNum, totalPages) {
    const slide = pptx.addSlide();
    slide.background = { color: COLORS.purpleDeep };
    const leftW = 5.4;

    slide.addText("YOUR NEXT MOVE", { x: MARGIN, y: 1.4, w: leftW, h: 0.32, fontSize: 12, bold: true, color: COLORS.gold, charSpacing: 2, fontFace: FONT });
    slide.addText("Turn your plan\ninto action.", { x: MARGIN, y: 1.85, w: leftW, h: 1.8, fontSize: 34, bold: true, color: COLORS.white, fontFace: FONT, lineSpacingMultiple: 1.08 });
    slide.addShape("line", { x: MARGIN, y: 3.85, w: 0.7, h: 0, line: { color: COLORS.gold, width: 3 } });

    const rightX = MARGIN + leftW + 0.6;
    const rightW = PAGE_W - MARGIN - rightX;
    const stepGap = Math.min(0.85, (5.6 - 1.35) / Math.max(1, n.closingSteps.length));
    n.closingSteps.forEach((step, i) => {
        const y = 1.5 + i * stepGap;
        DS.numberBadge(slide, { x: rightX, y, d: 0.42, text: i + 1, fill: COLORS.rose, textColor: COLORS.purpleDeep, fontSize: 14 });
        slide.addText(step, { x: rightX + 0.62, y: y + 0.02, w: rightW - 0.62, h: 0.5, fontSize: 15, color: COLORS.white, fontFace: FONT, valign: "middle" });
        if (i < n.closingSteps.length - 1) slide.addShape("line", { x: rightX + 0.21, y: y + 0.42, w: 0, h: stepGap - 0.42, line: { color: "6E4E7E", width: 1.5 } });
    });

    slide.addShape("line", { x: MARGIN, y: PAGE_H - 1.1, w: PAGE_W - MARGIN * 2, h: 0, line: { color: COLORS.gold, width: 1 } });
    slide.addText(
        [{ text: "IVY", options: { color: COLORS.white, bold: true } }, { text: "huts", options: { color: COLORS.goldLight, bold: true } }, { text: "   Housing to Hiring", options: { color: "C9B4C4", bold: false } }],
        { x: MARGIN, y: PAGE_H - 0.92, w: 8, h: 0.4, fontSize: 14, fontFace: FONT }
    );
    slide.addText(`${pageNum} / ${totalPages}`, { x: PAGE_W - MARGIN - 1.0, y: PAGE_H - 0.6, w: 1.0, h: 0.3, fontSize: 9, color: "9C82A0", align: "right", fontFace: FONT });
    return slide;
}

// Builds the full presentation from an already-normalized model
// (./pptNormalize.js's output -- untouched by this redesign). Conditional
// slides are simply omitted when their section's data isn't available --
// Cover, Journey and Closing always render.
function buildPresentation(normalized) {
    const pptx = new PptxGenJS();
    pptx.layout = "LAYOUT_WIDE";
    pptx.author = "IVYHUTS";
    pptx.company = "IVYHUTS";
    pptx.title = "IVYHUTS Student Plan";
    pptx.subject = "Housing to Hiring Student Plan";

    buildCoverSlide(pptx, normalized);

    const builders = [];
    if (normalized.university.available) builders.push(buildUniversitySlide);
    if (normalized.residences.length > 0) builders.push(buildResidencesSlide);
    if (normalized.comparison.length > 0) builders.push(buildComparisonSlide);
    if (normalized.livingExpenses.available) builders.push(buildLivingCostsSlide);
    if (normalized.degree.available) builders.push(buildDegreeSlide);
    if (normalized.careers.length > 0) builders.push(buildCareersSlide);
    if (normalized.salary.available) builders.push(buildSalarySlide);
    if (normalized.readiness.available) {
        builders.push(buildHiringPathSlide);
        if (normalized.readiness.preparationSteps.length > 0) builders.push(buildPreparationSlide);
    }
    builders.push(buildJourneySlide);
    builders.push(buildClosingSlide);

    const totalPages = 1 + builders.length; // +1 for the cover slide
    builders.forEach((build, i) => build(pptx, normalized, i + 2, totalPages));

    return pptx;
}

async function generateStudentPlanPptxBuffer(normalized) {
    const pptx = buildPresentation(normalized);
    const buffer = await pptx.write({ outputType: "nodebuffer" });
    return buffer;
}

