    const { slide } = DS.frame(pptx, { sectionLabel: "Hiring", title: "Suggested Preparation Path" });
    slide.addText("An indicative sequence -- not a required or guaranteed path.", { x: MARGIN, y: CONTENT_TOP, w: CONTENT_W, h: 0.3, fontSize: 11.5, italic: true, color: COLORS.inkFaint, fontFace: FONT });

    const steps = n.readiness.preparationSteps;
    const rowY = CONTENT_TOP + 1.0;
